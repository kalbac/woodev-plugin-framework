<?php
/**
 * Dev tool: regenerate woodev/class-map.php by scanning the framework tree.
 *
 * Usage: php bin/generate-class-map.php
 * NOT shipped — lives in bin/, never required at runtime.
 *
 * @package Woodev\Framework
 */

declare( strict_types=1 );

/*
 * Naming-convention table — the single place these rules live (see #647).
 * docs-internal/AGENT-RULES.md points here rather than restating the rules.
 */

// Rule 1: a namespace segment right after `Woodev\Framework\` maps to a directory of the
// same name UNLESS aliased here. Every other segment (including nested ones) maps to its
// own kebab-case form (Rest_Api -> rest-api). A class placed in a directory that doesn't
// match its namespace this way is the #647 "outlier" failure mode.
const WOODEV_NAMESPACE_DIR_ALIASES = [
	'Shipping' => 'shipping-method',
	'Settings' => 'settings-page',
];

// Rule 2: for a class named `Abstract_*`, the `Abstract_` is dropped from the file name
// because the file's own `abstract-` prefix already says so (Abstract_Shipment_Handler ->
// abstract-shipment-handler.php). Grandfathered: predate this gate, out of scope for #647
// (renaming touches only the map — verified low-risk — but is not part of this card's job).
const WOODEV_RULE2_GRANDFATHERED = [
	'Woodev\\Framework\\Shipping\\Api\\Abstract_Shipping_API',
	'Woodev\\Framework\\Shipping\\Pickup\\Abstract_Warehouse_Store',
];

// Rule 3: for a legacy (un-namespaced) class named `Woodev_*`, the `Woodev_` is dropped
// from the file name (Woodev_API_Base -> class-api-base.php). Grandfathered: predate this
// gate; their file names are `require`d by literal path from woodev/class-plugin.php and
// listed in composer.json, so renaming is a bootstrap-risk change out of scope for #647.
const WOODEV_RULE3_GRANDFATHERED = [
	'Woodev_Async_Request',
	'Woodev_Background_Job_Handler',
	'Woodev_Hook_Deprecator',
	'Woodev_Job_Batch_Handler',
	'Woodev_Plugin_Dependencies',
];

$root      = dirname( __DIR__ );
$framework = $root . '/woodev';

// Files loaded explicitly (bootstrap / loader / the autoloader+map themselves) — never autoloaded.
$skip = [
	'woodev/bootstrap.php',
	'woodev/loader.php',
	'woodev/class-map.php',
	'woodev/class-framework-autoloader.php',
];

$map = [];

$iterator = new RecursiveIteratorIterator(
	new RecursiveDirectoryIterator( $framework, FilesystemIterator::SKIP_DOTS )
);

/** @var SplFileInfo $file */
foreach ( $iterator as $file ) {
	if ( 'php' !== strtolower( $file->getExtension() ) ) {
		continue;
	}

	$relative = str_replace( '\\', '/', substr( $file->getPathname(), strlen( $root ) + 1 ) );

	if ( in_array( $relative, $skip, true ) ) {
		continue;
	}

	$symbols = woodev_extract_symbols( (string) file_get_contents( $file->getPathname() ) );

	foreach ( $symbols as $fqcn ) {
		if ( isset( $map[ $fqcn ] ) ) {
			fwrite( STDERR, sprintf( "DUPLICATE class %s in %s and %s\n", $fqcn, $map[ $fqcn ], $relative ) );
			exit( 1 );
		}
		$map[ $fqcn ] = $relative;
	}
}

ksort( $map );

$violations = woodev_verify_naming_rules( $map );
if ( [] !== $violations ) {
	fwrite( STDERR, "Naming-convention violations (see bin/generate-class-map.php rule table):\n" );
	foreach ( $violations as $violation ) {
		fwrite( STDERR, "  - {$violation}\n" );
	}
	exit( 1 );
}

$export  = "<?php\n";
$export .= "/**\n * GENERATED by bin/generate-class-map.php — do not edit by hand.\n";
$export .= " * Maps framework class/interface/trait FQCN => path relative to the framework copy root.\n";
$export .= " *\n * @package Woodev\\Framework\n */\n\n";
$export .= "return [\n";
foreach ( $map as $fqcn => $path ) {
	$export .= sprintf( "\t%s => %s,\n", var_export( $fqcn, true ), var_export( $path, true ) );
}
$export .= "];\n";

if ( false === file_put_contents( $framework . '/class-map.php', $export ) ) {
	fwrite( STDERR, "Failed to write woodev/class-map.php\n" );
	exit( 1 );
}

fwrite( STDOUT, sprintf( "Wrote %d entries to woodev/class-map.php\n", count( $map ) ) );

/**
 * Verifies the three naming conventions documented in the rule table above.
 *
 * @param array<string,string> $map FQCN => relative path.
 * @return string[] Human-readable violation messages; empty when the map is clean.
 */
function woodev_verify_naming_rules( array $map ): array {
	$violations = [];

	foreach ( $map as $fqcn => $path ) {
		$last_backslash = strrpos( $fqcn, '\\' );
		$short_name     = false === $last_backslash ? $fqcn : substr( $fqcn, $last_backslash + 1 );
		$basename       = basename( $path );

		// Rule 1 — namespace segments (after Woodev\Framework\) must match the directory.
		if ( 0 === strpos( $fqcn, 'Woodev\\Framework\\' ) ) {
			$rest     = substr( $fqcn, strlen( 'Woodev\\Framework\\' ) );
			$segments = explode( '\\', $rest );
			array_pop( $segments ); // Drop the class/interface/trait name itself.

			$expected_parts = [];
			foreach ( $segments as $index => $segment ) {
				if ( 0 === $index && isset( WOODEV_NAMESPACE_DIR_ALIASES[ $segment ] ) ) {
					$expected_parts[] = WOODEV_NAMESPACE_DIR_ALIASES[ $segment ];
					continue;
				}
				$expected_parts[] = strtolower( str_replace( '_', '-', $segment ) );
			}

			$expected_dir = implode( '/', array_merge( [ 'woodev' ], $expected_parts ) );
			$actual_dir   = str_replace( '\\', '/', dirname( $path ) );

			if ( $expected_dir !== $actual_dir ) {
				$violations[] = sprintf(
					'%s: namespace implies directory "%s" but the file is in "%s"',
					$fqcn,
					$expected_dir,
					$actual_dir
				);
			}
		}

		// Rule 2 — `Abstract_` is dropped from the file name; the file uses the `abstract-`
		// kind prefix instead of repeating the word after `class-`.
		//
		// The expected basename is COMPUTED and compared exactly, not merely prefix-checked
		// (critic finding, s104): a prefix test alone accepts
		// `abstract-abstract-shipment-handler.php`, which is precisely the repetition this rule
		// exists to forbid — a gate that passes the thing it names is not a gate.
		if ( 1 === preg_match( '/^Abstract_/', $short_name )
			&& ! in_array( $fqcn, WOODEV_RULE2_GRANDFATHERED, true )
		) {
			$expected_basename = 'abstract-' . strtolower( str_replace( '_', '-', substr( $short_name, strlen( 'Abstract_' ) ) ) ) . '.php';

			if ( $expected_basename !== $basename ) {
				$violations[] = sprintf( '%s: class name starts with Abstract_, so the file must be "%s", not "%s"', $fqcn, $expected_basename, $basename );
			}
		}

		// Rule 3 — `Woodev_` is dropped from a legacy class's file name.
		if ( false === strpos( $fqcn, '\\' )
			&& 1 === preg_match( '/^Woodev_/', $short_name )
			&& ! in_array( $fqcn, WOODEV_RULE3_GRANDFATHERED, true )
		) {
			foreach ( [ 'class-', 'abstract-', 'interface-', 'trait-' ] as $kind_prefix ) {
				if ( 0 === strpos( $basename, $kind_prefix ) ) {
					$tail = substr( $basename, strlen( $kind_prefix ) );
					if ( 0 === strpos( $tail, 'woodev-' ) ) {
						$violations[] = sprintf( '%s: class name starts with Woodev_ but file "%s" still spells it out', $fqcn, $basename );
					}
					break;
				}
			}
		}
	}

	return $violations;
}

/**
 * Extracts fully-qualified class/interface/trait names from PHP source via tokens.
 *
 * @param string $source PHP source.
 * @return string[] FQCNs.
 */
function woodev_extract_symbols( string $source ): array {
	$tokens    = token_get_all( $source );
	$namespace = '';
	$symbols   = [];
	$count     = count( $tokens );

	for ( $i = 0; $i < $count; $i++ ) {
		$token = $tokens[ $i ];

		if ( is_array( $token ) && T_NAMESPACE === $token[0] ) {
			$namespace = '';
			for ( $j = $i + 1; $j < $count; $j++ ) {
				$next = $tokens[ $j ];
				if ( ';' === $next || '{' === $next ) {
					break;
				}
				if ( is_array( $next ) && in_array( $next[0], [ T_STRING, T_NS_SEPARATOR ], true ) ) {
					$namespace .= $next[1];
				}
				if ( is_array( $next ) && defined( 'T_NAME_QUALIFIED' ) && T_NAME_QUALIFIED === $next[0] ) {
					$namespace .= $next[1];
				}
			}
			continue;
		}

		$class_like = [ T_CLASS, T_INTERFACE, T_TRAIT ];
		if ( defined( 'T_ENUM' ) ) {
			$class_like[] = T_ENUM;
		}

		if ( is_array( $token ) && in_array( $token[0], $class_like, true ) ) {
			// Skip `::class` and anonymous classes.
			$prev = $tokens[ $i - 1 ] ?? null;
			if ( is_array( $prev ) && T_DOUBLE_COLON === $prev[0] ) {
				continue;
			}
			for ( $j = $i + 1; $j < $count; $j++ ) {
				$next = $tokens[ $j ];
				if ( is_array( $next ) && T_WHITESPACE === $next[0] ) {
					continue;
				}
				if ( is_array( $next ) && T_STRING === $next[0] ) {
					$symbols[] = '' !== $namespace ? $namespace . '\\' . $next[1] : $next[1];
				}
				break;
			}
		}
	}

	return $symbols;
}
